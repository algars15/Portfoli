document.addEventListener("DOMContentLoaded", () => {

  // 1. Hover i Reproducció de Vídeos en Targetes
  const projectCards = document.querySelectorAll(".project-card");
  projectCards.forEach(card => {
    const video = card.querySelector(".project-card-video");
    if (!video) return;

    video.muted = true;
    video.defaultMuted = true;

    card.addEventListener("mouseenter", () => {
      video.muted = true;
      const playPromise = video.play();
      if (playPromise !== undefined) {
        playPromise.catch(error => console.warn("Reproducció cancel·lada:", error));
      }
    });

    card.addEventListener("mouseleave", () => {
      video.pause();
      video.currentTime = 0;
    });
  });

  // 2. Transició Slides de Fons al Hero
  const bgSlides = document.querySelectorAll(".hero-bg-slide");
  if (bgSlides.length > 0) {
    let currentIndex = 0;
    setInterval(() => {
      const previousIndex = currentIndex;
      currentIndex = (currentIndex + 1) % bgSlides.length;

      bgSlides[previousIndex].classList.remove("active");
      bgSlides[previousIndex].classList.add("exit-left");

      bgSlides[currentIndex].classList.remove("exit-left");
      bgSlides[currentIndex].classList.add("active");

      setTimeout(() => {
        bgSlides[previousIndex].classList.remove("exit-left");
      }, 1200);
    }, 5000);
  }

  // 3. Animació de Scroll (Reveal d'elements incloent la secció #about)
  const elementsToAnimate = document.querySelectorAll(
    "#about, .project-card, .skill-card, .about-hero-card, .contact-card"
  );

  elementsToAnimate.forEach((el) => el.classList.add("reveal"));

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("active");
      } else {
        entry.target.classList.remove("active");
      }
    });
  }, { threshold: 0.1 });

  elementsToAnimate.forEach((el) => observer.observe(el));

  // 4. Efecte Tilt 3D a les Targetes de Projectes
  projectCards.forEach((card) => {
    card.addEventListener("mousemove", (e) => {
      const rect = card.getBoundingClientRect();
      const x = e.clientX - rect.left;
      const y = e.clientY - rect.top;

      const centerX = rect.width / 2;
      const centerY = rect.height / 2;

      const rotateX = ((y - centerY) / centerY) * -4;
      const rotateY = ((x - centerX) / centerX) * 4;

      card.style.transform = `perspective(1000px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) scale3d(1.02, 1.02, 1.02)`;
    });

    card.addEventListener("mouseleave", () => {
      card.style.transform = `perspective(1000px) rotateX(0deg) rotateY(0deg) scale3d(1, 1, 1)`;
    });
  });

  // 5. Cursor Estrella Fugaç (Ocult directament en mòbils / pantalles tàctils)
  const cursorDot = document.querySelector(".star-cursor-dot");
  const canvas = document.getElementById("cursor-canvas");

  const isMobile = window.matchMedia("(hover: none) and (pointer: coarse)").matches || window.innerWidth <= 768;

  if (isMobile) {
    if (cursorDot) cursorDot.remove();
    if (canvas) canvas.remove();
  } else if (cursorDot && canvas) {
    const ctx = canvas.getContext("2d");
    let points = [];

    function resizeCanvas() {
      canvas.width = window.innerWidth;
      canvas.height = window.innerHeight;
    }
    window.addEventListener("resize", resizeCanvas);
    resizeCanvas();

    window.addEventListener("mousemove", (e) => {
      const x = e.clientX;
      const y = e.clientY;

      cursorDot.style.left = `${x}px`;
      cursorDot.style.top = `${y}px`;

      points.push({ x, y, life: 1.0 });
    });

    function renderShootingStar() {
      ctx.clearRect(0, 0, canvas.width, canvas.height);

      if (points.length > 1) {
        for (let i = 0; i < points.length - 1; i++) {
          const pt1 = points[i];
          const pt2 = points[i + 1];

          ctx.beginPath();
          ctx.moveTo(pt1.x, pt1.y);
          ctx.lineTo(pt2.x, pt2.y);

          ctx.lineWidth = (i / points.length) * 4;
          ctx.strokeStyle = `rgba(237, 174, 73, ${pt1.life})`;
          ctx.lineCap = "round";
          ctx.stroke();

          pt1.life -= 0.04;
        }

        points = points.filter((p) => p.life > 0);
      }

      requestAnimationFrame(renderShootingStar);
    }

    renderShootingStar();

    const interactiveElements = document.querySelectorAll(
      "a, button, .project-card, .btn-secondary, input, textarea, .skill-card"
    );

    interactiveElements.forEach((el) => {
      el.addEventListener("mouseenter", () => document.body.classList.add("cursor-hover"));
      el.addEventListener("mouseleave", () => document.body.classList.remove("cursor-hover"));
    });
  }

  // 6. Scrollspy per al Menú de Navegació
  const navLinks = document.querySelectorAll(".nav-links a");
  const allSections = document.querySelectorAll("section[id]");

  window.addEventListener("scroll", () => {
    let currentSectionId = "";
    const scrollPosition = window.scrollY + 200;

    allSections.forEach((sec) => {
      if (scrollPosition >= sec.offsetTop) {
        currentSectionId = sec.getAttribute("id");
      }
    });

    navLinks.forEach((link) => {
      link.classList.remove("active");
      if (link.getAttribute("href") === `#${currentSectionId}`) {
        link.classList.add("active");
      }
    });
  });

});